#!/usr/bin/env python3
"""Generate fish completions for hunk from its zsh completion script.

hunk ships completion generators for bash and zsh only. The zsh script carries
the whole command tree as data (one `case` arm per command node, with zsh
`_arguments` specs and subcommand items), so this script parses those arms and
emits the equivalent fish `complete` calls, plus a few dynamic completions the
zsh script lacks (git refs, stash entries, extension ids, `hunk gh`).

Usage: hunk/fish-completion.py > fish/completions/hunk.fish
Rerun after upgrading hunk.
"""

import re
import shlex
import subprocess
import sys

ARM = re.compile(r"^    '(?P<node>[^']*)'\) args=\((?P<args>.*)\); items=\((?P<items>.*)\) ;;$")
OPTION = re.compile(
    r"^\*?(?P<flag>-[^\[=+]+)(?P<suffix>[=+]?)"
    r"\[(?P<desc>(?:\\.|[^\]])*)\]"
    r"(?::(?P<message>[^:]*):(?P<action>.*))?$"
)
UNESCAPED_COLON = re.compile(r"(?<!\\):")

# Positional completions the zsh script leaves to `_files`. Keyed by command node.
GIT_REF_NODES = (" diff", " show", " log")


def unescape(text):
    return text.replace("\\:", ":")


def fish_quote(text):
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"


def parse(zsh):
    nodes = {}
    for line in zsh.splitlines():
        match = ARM.match(line)
        if not match:
            continue
        options = []
        for spec in shlex.split(match["args"]):
            option = OPTION.match(spec)
            if option:
                options.append(option)
            elif not re.match(r"^\*?\d*:(command|path):->(command|path)$", spec):
                sys.exit(f"unrecognized option spec in {match['node']!r}: {spec}")
        items = [UNESCAPED_COLON.split(item, maxsplit=1) for item in shlex.split(match["items"])]
        nodes[match["node"]] = (options, items)
    if "" not in nodes or " diff" not in nodes:
        sys.exit("no command nodes found; has the zsh completion format changed?")
    return nodes


def option_line(node, option):
    flag = option["flag"]
    parts = ["complete -c hunk", f"-n {fish_quote(f'__hunk_node_is {fish_quote(node)}')}"]
    parts.append(f"-l {flag[2:]}" if flag.startswith("--") else f"-s {flag[1:]}")
    if option["suffix"]:
        parts.append("-r")
        action = option["action"] or ""
        choices = re.fullmatch(r"\((.*)\)", action)
        if choices:
            parts += ["-f", "-a", fish_quote(choices[1])]
        elif flag in ("--disable-extension", "--enable-extension"):
            parts += ["-f", "-a", fish_quote("(__hunk_extension_ids)")]
        elif action == "_files":
            parts.append("-F")
    parts += ["-d", fish_quote(unescape(option["desc"]))]
    return " ".join(parts)


def item_line(node, item):
    name, desc = (item + [""])[:2]
    parts = [
        "complete -c hunk",
        f"-n {fish_quote(f'__hunk_node_is {fish_quote(node)}')}",
        f"-f -a {fish_quote(name)}",
    ]
    if desc:
        parts += ["-d", fish_quote(unescape(desc))]
    return " ".join(parts)


def emit(nodes, version):
    out = []
    w = out.append
    w(f"# Generated by hunk/fish-completion.py from `hunk completion zsh` (hunk {version}).")
    w("# Do not edit by hand; rerun the generator after upgrading hunk.")
    w("")
    w("# Walks the command line the way the zsh script does: known command words")
    w("# extend the node, options that take a separate value swallow the next word,")
    w("# and `--` ends option parsing. Cached per command line, since every")
    w("# `complete` condition below calls it.")
    w("function __hunk_node")
    w("    set -l line (commandline -pc)")
    w("    if test \"$line\" = \"$__hunk_node_line\"")
    w("        echo $__hunk_node_cached")
    w("        return")
    w("    end")
    w("    set -l node ''")
    w("    set -l skip 0")
    w("    for word in (commandline -xpc)[2..]")
    w("        if test $skip = 1")
    w("            set skip 0")
    w("            continue")
    w("        end")
    w("        if test \"$word\" = --")
    w("            set node \"$node --\"")
    w("            break")
    w("        end")
    w("        switch \"$node $word\"")
    w("            case " + " ".join(fish_quote(n) for n in sorted(nodes) if n) + " ' gh' ' gh pr' ' gh commit' ' gh compare'")
    w("                set node \"$node $word\"")
    w("                continue")
    w("        end")
    w("        string match -q -- '*=*' $word; and continue")
    w("        switch \"$node $word\"")
    value_flags = sorted(
        f"{node} {option['flag']}"
        for node, (options, _) in nodes.items()
        for option in options
        if option["suffix"]
    )
    w("            case " + " ".join(fish_quote(f) for f in value_flags) + " ' gh pr --repo' ' gh commit --repo' ' gh compare --repo'")
    w("                set skip 1")
    w("        end")
    w("    end")
    w("    set -g __hunk_node_line $line")
    w("    set -g __hunk_node_cached $node")
    w("    echo $node")
    w("end")
    w("")
    w("function __hunk_node_is")
    w("    test (__hunk_node) = \"$argv[1]\"")
    w("end")
    w("")
    w("function __hunk_git_refs")
    w("    command git rev-parse --git-dir >/dev/null 2>&1; or return")
    w("    printf '%s\\tref\\n' HEAD")
    w("    command git for-each-ref --format='%(refname:short)%09branch' refs/heads")
    w("    command git for-each-ref --format='%(refname:short)%09remote branch' refs/remotes")
    w("    command git for-each-ref --format='%(refname:short)%09tag' refs/tags")
    w("end")
    w("")
    w("function __hunk_stash_refs")
    w("    command git stash list --format='%gd%x09%s' 2>/dev/null")
    w("end")
    w("")
    w("function __hunk_extension_ids")
    w("    hunk extension list 2>/dev/null | string split -f1 ' '")
    w("end")
    w("")
    w("complete -c hunk -e")
    w("")
    for node in sorted(nodes):
        options, items = nodes[node]
        w(f"# hunk{node}")
        for item in items:
            w(item_line(node, item))
        for option in options:
            w(option_line(node, option))
        w("")
    w("# Dynamic positionals the zsh script leaves to file completion.")
    for node in GIT_REF_NODES:
        w(f"complete -c hunk -n {fish_quote(f'__hunk_node_is {fish_quote(node)}')} -k -a '(__hunk_git_refs)'")
    w("complete -c hunk -n \"__hunk_node_is ' stash show'\" -f -k -a '(__hunk_stash_refs)'")
    for node in (" extension update", " extension remove", " ext update", " ext remove"):
        w(f"complete -c hunk -n {fish_quote(f'__hunk_node_is {fish_quote(node)}')} -f -a '(__hunk_extension_ids)'")
    w("")
    w("# hunk gh is a bundled extension command, so the zsh script omits it.")
    w("complete -c hunk -n \"__hunk_node_is ''\" -f -a gh -d 'review changes hosted on GitHub'")
    w("complete -c hunk -n \"__hunk_node_is ' gh'\" -f -a pr -d 'review a GitHub pull request'")
    w("complete -c hunk -n \"__hunk_node_is ' gh'\" -f -a commit -d 'review a GitHub commit'")
    w("complete -c hunk -n \"__hunk_node_is ' gh'\" -f -a compare -d 'review the changes between two GitHub refs'")
    for sub in ("pr", "commit", "compare"):
        w(f"complete -c hunk -n \"__hunk_node_is ' gh {sub}'\" -f -l repo -r -d 'use an explicit owner/repo instead of the local origin'")
    return "\n".join(out) + "\n"


def main():
    zsh = subprocess.run(["hunk", "completion", "zsh"], check=True, capture_output=True, text=True).stdout
    version = subprocess.run(["hunk", "--version"], check=True, capture_output=True, text=True).stdout.strip()
    sys.stdout.write(emit(parse(zsh), version))


if __name__ == "__main__":
    main()
